
import API_BASE_URL from "../api";
import { customerAuthenticatedFetch } from "../customerAuthenticatedFetch";
import {
  getSessionRole,
  getSessionToken,
} from "../auth/authStorage";

// The backend cart line.
export type CartItem = {
  id: number | string;
  product_id: number | string;
  name: string;
  business_name: string;
  image: string | null;
  unit_price: string;
  quantity: number;
  line_total: string;
  available: boolean;
  issue: string | null;
  max_quantity: number;
};

// The complete cart returned by the backend.
export type CartResponse = {
  items: CartItem[];
  total_quantity: number;
  total: string;
  has_unavailable_items: boolean;
  cart_token: string | null;
};

// Data required when adding a product.
export type AddCartItemData = {
  product: number | string;
  quantity: number;
};

export const CART_TOKEN_KEY = "pawdigree:cart_token";

// Build the full backend URL.
function getCartUrl(endpoint: string): string {
  if (!API_BASE_URL) {
    throw new Error("The backend API URL is not configured.");
  }

  return new URL(`/api/cart${endpoint}`, API_BASE_URL).toString();
}

// Read and format backend errors.
async function getErrorMessage(response: Response): Promise<string> {
  const data: unknown = await response.json().catch(() => null);

  if (data && typeof data === "object") {
    const errors = data as Record<string, unknown>;

    const message = Object.entries(errors)
      .map(([field, value]) => {
        const readableValue = Array.isArray(value)
          ? value.join(" ")
          : typeof value === "string"
            ? value
            : JSON.stringify(value);

        return field === "detail"
          ? readableValue
          : `${field}: ${readableValue}`;
      })
      .join("\n");

    if (message) return message;
  }

  return `Cart request failed (${response.status}).`;
}

// Handle successful responses that contain a cart.
async function handleResponse(response: Response): Promise<CartResponse> {
  if (!response.ok) {
    throw new Error(await getErrorMessage(response));
  }

  const data: unknown = await response.json().catch(() => null);

  if (!data || typeof data !== "object") {
    throw new Error("The backend returned an invalid cart response.");
  }

  return data as CartResponse;
}

// Handle DELETE responses that return 204 No Content.
async function handleNoContentResponse(response: Response): Promise<void> {
  if (!response.ok) {
    throw new Error(await getErrorMessage(response));
  }
}

// Save the guest token returned by the backend.
function saveGuestCartToken(cart: CartResponse): void {
  if (cart.cart_token) {
    localStorage.setItem(CART_TOKEN_KEY, cart.cart_token);
  }
}

// Send a cart request using the correct authentication method.
async function sendCartRequest(
  endpoint: string,
  options: RequestInit = {},
): Promise<Response> {
  const role = getSessionRole();
  const accessToken = getSessionToken();

  // Only customer accounts can use the cart.
  if (role && role !== "CUSTOMER") {
    throw new Error("Only customer accounts can access the shopping cart.");
  }

  // A token without a recognised customer role must not be treated as a guest.
  if (accessToken && role !== "CUSTOMER") {
    throw new Error("Please log in with a customer account to use the cart.");
  }

  const headers = new Headers(options.headers);

  if (options.body) {
    headers.set("Content-Type", "application/json");
  }

  if (role === "CUSTOMER") {
    // Logged-in customers use their JWT.
    // Do not send the guest cart token during normal cart operations.
    return customerAuthenticatedFetch(getCartUrl(endpoint), {
      ...options,
      headers,
    });
  }

  // Guests use the token generated by the backend.
  const guestToken = localStorage.getItem(CART_TOKEN_KEY);

  if (guestToken) {
    headers.set("X-Cart-Token", guestToken);
  }

  return fetch(getCartUrl(endpoint), {
    ...options,
    headers,
  });
}

// Send a request and process a response containing the full cart.
async function cartRequest(
  endpoint: string,
  options: RequestInit = {},
): Promise<CartResponse> {
  const response = await sendCartRequest(endpoint, options);
  const cart = await handleResponse(response);

  // Keep the server-generated token for guest cart requests.
  if (!getSessionRole()) {
    saveGuestCartToken(cart);
  }

  return cart;
}

// GET /api/cart/
export function getCart(): Promise<CartResponse> {
  return cartRequest("/");
}

// POST /api/cart/items/
export function addCartItem(
  data: AddCartItemData,
): Promise<CartResponse> {
  if (!Number.isInteger(data.quantity) || data.quantity < 1) {
    throw new Error("Quantity must be at least 1.");
  }

  return cartRequest("/items/", {
    method: "POST",
    body: JSON.stringify(data),
  });
}

// PATCH /api/cart/items/{item_id}/
export function updateCartItemQuantity(
  itemId: number | string,
  quantity: number,
): Promise<CartResponse> {
  if (!Number.isInteger(quantity) || quantity < 1) {
    throw new Error("Quantity must be at least 1.");
  }

  return cartRequest(`/items/${itemId}/`, {
    method: "PATCH",
    body: JSON.stringify({ quantity }),
  });
}

// DELETE /api/cart/items/{item_id}/
export async function removeCartItem(
  itemId: number | string,
): Promise<CartResponse> {
  const response = await sendCartRequest(`/items/${itemId}/`, {
    method: "DELETE",
  });

  // The backend confirms deletion with 204 and no response body.
  await handleNoContentResponse(response);

  // Retrieve the updated cart from the backend.
  return getCart();
}

// DELETE /api/cart/
export async function emptyCart(): Promise<CartResponse> {
  const response = await sendCartRequest("/", {
    method: "DELETE",
  });

  // The backend confirms deletion with 204 and no response body.
  await handleNoContentResponse(response);

  // Remove the guest token only after the backend confirms success.
  if (!getSessionRole()) {
    localStorage.removeItem(CART_TOKEN_KEY);
  }

  // A successful empty-cart response means the cart is now empty.
  return {
    items: [],
    total_quantity: 0,
    total: "0.00",
    has_unavailable_items: false,
    cart_token: null,
  };
}

// POST /api/cart/merge/
export async function mergeGuestCart(): Promise<CartResponse | null> {
  const guestToken = localStorage.getItem(CART_TOKEN_KEY);

  // Nothing to merge if the browser has no guest cart token.
  if (!guestToken) {
    return null;
  }

  if (getSessionRole() !== "CUSTOMER" || !getSessionToken()) {
    throw new Error("A logged-in customer account is required to merge carts.");
  }

  const response = await customerAuthenticatedFetch(
    getCartUrl("/merge/"),
    {
      method: "POST",
      headers: {
        "X-Cart-Token": guestToken,
      },
    },
  );

  const cart = await handleResponse(response);

  // Remove the guest token only after a successful merge.
  localStorage.removeItem(CART_TOKEN_KEY);

  return cart;
}
